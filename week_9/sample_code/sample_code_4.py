
# WEEK 9: VERSION 4
# GOAL: Connect our Streamlit interface to OpenAI.
#
# NEW CONCEPTS:
# 1. Reusing our existing API code
# 2. Saving previous_response_id in session state
# 3. Understanding two kinds of chatbot memory
#
# We already know how to call the OpenAI API.
# Now we're connecting it to our website!


import streamlit as st

# NEW: Bring back our imports from Week 7.
from dotenv import load_dotenv
from openai import OpenAI


# Load our API key from the .env file.
load_dotenv()

# Create our OpenAI client.
client = OpenAI()


# These are the same instructions from our old chatbot.
#
# They tell the AI how it should behave.
INSTRUCTIONS = """
You are a friendly study coach for high school students.

Explain things clearly.
Keep answers short.
Be encouraging.

Do not complete live graded tests or quizzes.
Instead, help the student understand the concept.
"""


st.title("My AI Chatbot")


# Set up the conversation history for our website.
#
# This is the same session state code from Version 3.
if "messages" not in st.session_state:
    st.session_state.messages = []


# NEW: Save the OpenAI conversation ID.
#
# Remember previous_response_id from Week 7?
#
# When we send a message to OpenAI, it returns
# a response with its own unique ID.
#
# When we send the next message, we can pass
# the previous response ID back to the API.
#
# This lets the model continue the conversation
# instead of treating every message as a new chat.
#
# We need to save this ID between Streamlit reruns.
if "previous_response_id" not in st.session_state:

    # None means there is no previous response yet.
    st.session_state.previous_response_id = None


# Display all previously saved messages.
for message in st.session_state.messages:

    with st.chat_message(message["role"]):
        st.write(message["content"])


# Get input from the user.
prompt = st.chat_input("Ask me anything!")


if prompt:

    # Save the user's message in our website history.
    st.session_state.messages.append({
        "role": "user",
        "content": prompt
    })

    # Display the user's message.
    st.chat_message("user").write(prompt)


    # NEW: Call the actual OpenAI API!
    #
    # This should look familiar from Week 7.
    #
    # The important difference is that our input
    # now comes from st.chat_input() instead of input().
    response = client.responses.create(
        model="gpt-6-luna",
        instructions=INSTRUCTIONS,
        input=prompt,

        # Get our saved previous response ID.
        # On the first message, this will be None.
        previous_response_id=st.session_state.previous_response_id
    )


    # NEW: Save the response ID we just received.
    #
    # We'll use it the next time the user sends a message.
    st.session_state.previous_response_id = response.id


    # Get the actual text generated by the AI.
    bot_reply = response.output_text


    # Save the AI response in our website history.
    st.session_state.messages.append({
        "role": "assistant",
        "content": bot_reply
    })


    # Display the AI response on the website.
    st.chat_message("assistant").write(bot_reply)


# IMPORTANT: WE NOW HAVE TWO KINDS OF MEMORY.
#
# 1. st.session_state.messages
#
# This stores the messages we want to display.
# It makes the chat history visible on our website.
#
# 2. st.session_state.previous_response_id
#
# This stores the ID of the last OpenAI response.
# It lets the API continue from previous context.
#
# These are not the same thing!
#
# The website could display old messages even if
# the AI wasn't using that conversation context.
#
# And the AI could remember previous context even
# if we weren't displaying those messages.
